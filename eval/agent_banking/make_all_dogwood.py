"""Write policies/dogwood/all.dw: the conjunction of the Dogwood policies (the
suppression parts of B1-B8 and B10; B9 only causes events).  Every write is
decided; the credential changes that B7 reads are therefore requests, and
suppressed ones (with a `denied` marker) do not count."""
import re
from pathlib import Path

D = Path(__file__).parent / "policies" / "dogwood"
WRITES = ["SendMoney", "Schedule", "Redirect", "Amend", "UpdatePassword", "UpdateUserInfo"]
parts = sorted((p for p in D.glob("b*.dw")), key=lambda p: int(p.name[1:].split("_")[0]))
body = []
for p in parts:
    src = p.read_text()
    # Drop the header comments/directives and the base permits.
    src = re.sub(r"(?m)^//.*\n", "", src)
    src = re.sub(r'@id\("[a-z]+"\)\npermit \(principal, action == L::Action::"\w+", resource\);\n', "", src)
    body.append(f"// ── {p.stem} ──\n" + src.strip() + "\n")
text = "\n".join(body)
for ev in ["UpdateUserInfo", "UpdatePassword"]:
    text = text.replace(
        f'formerly within 24h L::Action::"{ev}"::state{{ input.u: context.input.u }}',
        f'exists (rid: String). (formerly within 24h L::Action::"{ev}"::request{{ input.u: context.input.u, rid: rid }}\n'
        f'        && !formerly within 24h L::Action::"{ev}"::denied{{ rid: rid }})')
header = ("// Conjunction of the Dogwood policies (generated by make_all_dogwood.py).\n"
          f"// decide: {', '.join(WRITES)}\n// time-scale: 60\n\n")
permits = "".join(f'@id("{w.lower()}")\npermit (principal, action == L::Action::"{w}", resource);\n'
                  for w in WRITES)
(D / "all.dw").write_text(header + permits + "\n" + text)
print(f"all.dw: {len(parts)} policies")
