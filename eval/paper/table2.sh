#!/usr/bin/env bash
# Table 2 (tab:app1): GDPRSocial page latency, EnfFlash vs. the non-enforced baseline.
#
# Usage: eval/paper/table2.sh [--tools TOOLS] [--cache on|off] [-o OUT.tex]
#
#   --tools   tools to rerun, comma-separated, or "all": enfflash,baseline (default: none)
#   --cache   EnfFlash's result cache (instrlib), on or off              (default: on)
#   -o        LaTeX output          (default: $PAPER/tables/tab_app1.tex)
#
# Only the selected tools are rerun; the table is always regenerated from the
# latest run of each tool (proactive-enforcement-library/miniTwitter_gdpr/
# benchmark/privacy_testsuite/output/minitwitter_<policy>_<date>).
# The GDPRSocial policy (generated by Lex) needs EnfFlash's -fix-since option.
# Example: eval/paper/table2.sh --tools enfflash
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
source "$HERE/common.sh"

TOOLS="" CACHE=on OUT="$TABLES/tab_app1.tex"
while [[ $# -gt 0 ]]; do
    case "$1" in
        --tools) TOOLS="$(expand_list "$2" enfflash,baseline)"; shift 2 ;;
        --cache) CACHE="$2"; shift 2 ;;
        -o)      OUT="$2"; shift 2 ;;
        *) sed -n '2,15p' "$0"; exit 1 ;;
    esac
done
for t in $TOOLS; do in_list "$t" "enfflash baseline" || { echo "unknown tool $t"; exit 1; }; done

SUITE="$PEL/miniTwitter_gdpr/benchmark/privacy_testsuite"
export INSTRLIB_EXE="$ENFFLASH" INSTRLIB_EXTRA_ARGS="-fix-since"
POLICY_enfflash=minitwit_gdpr
POLICY_baseline=baseline

if [[ -n "$TOOLS" ]]; then
    (cd "$WHYENF" && dune build bin/enfflash.exe)
    pin_performance
    prepared=0
    for t in $TOOLS; do
        policy="POLICY_$t"; policy="${!policy}"
        # The snapshots (database + EnfFlash state) are shared by both tools:
        # build them once, with the enforced policy.
        SKIP_PREPARE=$prepared "$SUITE/run_benchmark.sh" "$policy" "$ENFFLASH" "$CACHE"
        prepared=1
    done
fi

mkdir -p "$(dirname "$OUT")"
suffix=""; [[ "$CACHE" == off ]] && suffix="_nocache"
cd "$SUITE"
"${PY:-/usr/bin/python3.12}" make_table.py -d output -p "minitwit_gdpr$suffix" -o "$OUT"
# The figure of this table (panel of fig:eval), from the same results.
"${PY:-/usr/bin/python3.12}" -W ignore "$HERE/figures.py" app1
